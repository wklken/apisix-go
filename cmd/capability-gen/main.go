func main() {
	if err := run(os.Args[1:], os.Stderr); err != nil {
		fmt.Fprintln(os.Stderr, err)
		os.Exit(1)
	}
}

func run(args []string, stderr io.Writer) error {
	flags := flag.NewFlagSet("capability-gen", flag.ContinueOnError)
	flags.SetOutput(stderr)
	repoRoot := flags.String("repo-root", ".", "repository root containing generated outputs")
	check := flags.Bool("check", false, "fail when generated outputs differ from disk")
	write := flags.Bool("write", false, "write generated outputs")
	if err := flags.Parse(args); err != nil {
		return err
	}
	if flags.NArg() != 0 {
		return fmt.Errorf("unexpected arguments: %s", strings.Join(flags.Args(), " "))
	}
	if *check == *write {
		return errors.New("exactly one of -check or -write must be set")
	}

	manifest, err := capability.Load()
	if err != nil {
		return fmt.Errorf("load capability manifest: %w", err)
	}
	outputs, err := buildValidatedOutputs(*repoRoot, manifest)
	if err != nil {
		return err
	}
	if *write {
		return writeOutputs(*repoRoot, outputs)
	}
	return checkOutputs(*repoRoot, outputs)
}

func buildValidatedOutputs(
	repoRoot string,
	manifest *capability.Manifest,
) ([]generatedOutput, error) {
	if err := validateEvidenceRefs(repoRoot, manifest); err != nil {
		return nil, err
	}
	return buildOutputs(repoRoot, manifest)
}

func buildOutputs(repoRoot string, manifest *capability.Manifest) ([]generatedOutput, error) {
	if manifest == nil {
		return nil, errors.New("build outputs: capability manifest must not be nil")
	}
	if err := validateDivergenceADRs(repoRoot, manifest); err != nil {
		return nil, err
	}
	registry, err := renderRegistry(manifest)
	if err != nil {
		return nil, err
	}
	plugins, err := renderPluginsMarkdown(manifest)
	if err != nil {
		return nil, err
	}

	root, err := openOutputRoot(repoRoot)
	if err != nil {
		return nil, err
	}
	defer func() { _ = root.Close() }()

	englishSource, err := readRootedFile(root, readmeOutputPath)
	if err != nil {
		return nil, err
	}
	englishSummary, err := renderReadmeSummary(manifest, readmeEnglish)
	if err != nil {
		return nil, err
	}
	english, err := replaceGeneratedReadmeBlock(englishSource, englishSummary)
	if err != nil {
		return nil, fmt.Errorf("replace %s generated summary: %w", readmeOutputPath, err)
	}

	chineseSource, err := readRootedFile(root, readmeChineseOutputPath)
	if err != nil {
		return nil, err
	}
	chineseSummary, err := renderReadmeSummary(manifest, readmeChinese)
	if err != nil {
		return nil, err
	}
	chinese, err := replaceGeneratedReadmeBlock(chineseSource, chineseSummary)
	if err != nil {
		return nil, fmt.Errorf("replace %s generated summary: %w", readmeChineseOutputPath, err)
	}

	return []generatedOutput{
		{relativePath: registryOutputPath, content: registry},
		{relativePath: pluginsOutputPath, content: plugins},
		{relativePath: readmeOutputPath, content: english},
		{relativePath: readmeChineseOutputPath, content: chinese},
	}, nil
}

func validateEvidenceRefs(repoRoot string, manifest *capability.Manifest) error {
	if manifest == nil {
		return errors.New("validate evidence refs: capability manifest must not be nil")
	}
	root, err := openOutputRoot(repoRoot)
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()

	for _, plugin := range manifest.Plugins {
		for _, evidence := range []struct {
			kind  capability.EvidenceKind
			claim capability.EvidenceClaim
		}{
			{capability.EvidenceSchema, plugin.Evidence.Schema},
			{capability.EvidenceUnit, plugin.Evidence.Unit},
			{capability.EvidenceUpstream, plugin.Evidence.Upstream},
			{capability.EvidenceDifferential, plugin.Evidence.Differential},
			{capability.EvidenceRealDependency, plugin.Evidence.RealDependency},
			{capability.EvidenceFailure, plugin.Evidence.Failure},
		} {
			if evidence.claim.State != capability.EvidenceVerified {
				continue
			}
			for _, ref := range evidence.claim.Refs {
				if err := validateEvidenceRef(root, ref); err != nil {
					return fmt.Errorf(
						"plugin %q evidence %q ref %q: %w",
						plugin.Name,
						evidence.kind,
						ref,
						err,
					)
				}
			}
		}
	}
	return nil
}

func validateEvidenceRef(root *os.Root, ref string) error {
	path, symbol, hasSymbol := strings.Cut(ref, "#")
	relativePath, err := containedOutputRelativePath(path)
	if err != nil {
		return err
	}
	if err := rejectRootedSymlinks(root, relativePath, "evidence ref"); err != nil {
		return err
	}
	content, err := root.ReadFile(relativePath)
	if errors.Is(err, os.ErrNotExist) {
		return errors.New("does not exist")
	}
	if err != nil {
		return fmt.Errorf("read file: %w", err)
	}
	if !hasSymbol {
		return nil
	}
	if symbol == "" || strings.Contains(symbol, "#") {
		return errors.New("has an invalid test symbol anchor")
	}
	parsed, err := parser.ParseFile(token.NewFileSet(), relativePath, content, 0)
	if err != nil {
		return fmt.Errorf("parse Go test file: %w", err)
	}
	for _, declaration := range parsed.Decls {
		function, ok := declaration.(*ast.FuncDecl)
		if ok && function.Recv == nil && function.Name.Name == symbol {
			return nil
		}
	}
	return fmt.Errorf("does not define test function %q", symbol)
}

func validateDivergenceADR(repoRoot string, divergence capability.Divergence) error {
	root, err := openOutputRoot(repoRoot)
	if err != nil {
		return fmt.Errorf("divergence %q: %w", divergence.ID, err)
	}
	defer func() { _ = root.Close() }()

	_, err = validateDivergenceADRInRoot(root, divergence)
	return err
}

func validateDivergenceADRs(repoRoot string, manifest *capability.Manifest) error {
	if manifest == nil {
		return errors.New("validate divergence ADRs: capability manifest must not be nil")
	}

	referenced := make(map[string]map[string]struct{})
	for _, divergence := range manifest.Divergences {
		if divergence.Status != capability.DivergenceAccepted {
			continue
		}
		if divergence.Target != manifest.Target.Name {
			return fmt.Errorf(
				"divergence %q: target %q does not match manifest target %q",
				divergence.ID,
				divergence.Target,
				manifest.Target.Name,
			)
		}
		relativePath, err := validateADRRelativePath(divergence.ADR)
		if err != nil {
			return fmt.Errorf("divergence %q: %w", divergence.ID, err)
		}
		if err := validateDivergenceADR(repoRoot, divergence); err != nil {
			return err
		}
		if referenced[relativePath] == nil {
			referenced[relativePath] = make(map[string]struct{})
		}
		referenced[relativePath][divergence.ID] = struct{}{}
	}

	root, err := openOutputRoot(repoRoot)
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()

	if err := rejectRootedSymlinks(root, adrDirectoryPath, "ADR directory"); err != nil {
		return err
	}
	directory, err := root.Open(adrDirectoryPath)
	if errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("ADR directory %q is missing", adrDirectoryPath)
	}
	if err != nil {
		return fmt.Errorf("open ADR directory %q: %w", adrDirectoryPath, err)
	}
	defer func() { _ = directory.Close() }()

	entries, err := directory.ReadDir(-1)
	if err != nil {
		return fmt.Errorf("read ADR directory %q: %w", adrDirectoryPath, err)
	}
	sort.Slice(entries, func(i, j int) bool { return entries[i].Name() < entries[j].Name() })
	for _, entry := range entries {
		if entry.IsDir() || filepath.Ext(entry.Name()) != ".md" {
			continue
		}
		relativePath := filepath.ToSlash(filepath.Join(adrDirectoryPath, entry.Name()))
		if err := rejectRootedSymlinks(root, relativePath, "ADR path"); err != nil {
			return err
		}
		content, err := root.ReadFile(filepath.FromSlash(relativePath))
		if err != nil {
			return fmt.Errorf("read ADR %q: %w", relativePath, err)
		}
		frontMatter, err := parseADR(relativePath, content)
		if err != nil {
			return err
		}
		if frontMatter.Status == string(capability.DivergenceAccepted) {
			expectedIDs, ok := referenced[relativePath]
			if !ok {
				return fmt.Errorf(
					"accepted ADR %q (%s) is unreferenced by an accepted manifest divergence",
					relativePath,
					frontMatter.ID,
				)
			}
			actualIDs := make(map[string]struct{}, len(frontMatter.DivergenceIDs))
			for _, divergenceID := range frontMatter.DivergenceIDs {
				if _, duplicate := actualIDs[divergenceID]; duplicate {
					return fmt.Errorf(
						"accepted ADR %q (%s) contains duplicate divergence id %q",
						relativePath,
						frontMatter.ID,
						divergenceID,
					)
				}
				actualIDs[divergenceID] = struct{}{}
			}
			if len(actualIDs) != len(expectedIDs) {
				return fmt.Errorf(
					"accepted ADR %q (%s) divergence_ids do not exactly match accepted manifest divergences",
					relativePath,
					frontMatter.ID,
				)
			}
			for divergenceID := range expectedIDs {
				if _, ok := actualIDs[divergenceID]; !ok {
					return fmt.Errorf(
						"accepted ADR %q (%s) divergence_ids do not exactly match accepted manifest divergences; missing %q",
						relativePath,
						frontMatter.ID,
						divergenceID,
					)
				}
			}
		}
	}
	return nil
}

func validateDivergenceADRInRoot(
	root *os.Root,
	divergence capability.Divergence,
) (adrFrontMatter, error) {
	if divergence.Status != capability.DivergenceAccepted {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: status %q is not active",
			divergence.ID,
			divergence.Status,
		)
	}
	if strings.TrimSpace(divergence.OwnerApprovalRef) == "" {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: owner_approval_ref must not be blank",
			divergence.ID,
		)
	}
	relativePath, err := validateADRRelativePath(divergence.ADR)
	if err != nil {
		return adrFrontMatter{}, fmt.Errorf("divergence %q: %w", divergence.ID, err)
	}
	if err := rejectRootedSymlinks(root, filepath.FromSlash(relativePath), "ADR path"); err != nil {
		return adrFrontMatter{}, fmt.Errorf("divergence %q: %w", divergence.ID, err)
	}
	content, err := root.ReadFile(filepath.FromSlash(relativePath))
	if errors.Is(err, os.ErrNotExist) {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: missing ADR %q",
			divergence.ID,
			relativePath,
		)
	}
	if err != nil {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: read ADR %q: %w",
			divergence.ID,
			relativePath,
			err,
		)
	}
	frontMatter, err := parseADR(relativePath, content)
	if err != nil {
		return adrFrontMatter{}, fmt.Errorf("divergence %q: %w", divergence.ID, err)
	}

	filenameID, err := adrIDFromPath(relativePath)
	if err != nil {
		return adrFrontMatter{}, fmt.Errorf("divergence %q: %w", divergence.ID, err)
	}
	if frontMatter.ID != filenameID {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: ADR id %q does not match filename id %q",
			divergence.ID,
			frontMatter.ID,
			filenameID,
		)
	}
	if frontMatter.Status != string(capability.DivergenceAccepted) {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: ADR %q status %q is not accepted",
			divergence.ID,
			relativePath,
			frontMatter.Status,
		)
	}
	if frontMatter.Owner != "wklken" {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: ADR %q owner %q must be wklken",
			divergence.ID,
			relativePath,
			frontMatter.Owner,
		)
	}
	if frontMatter.Target != divergence.Target {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: ADR target %q does not match manifest value %q",
			divergence.ID,
			frontMatter.Target,
			divergence.Target,
		)
	}
	if frontMatter.OwnerApprovalRef != divergence.OwnerApprovalRef {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: ADR owner_approval_ref %q does not match manifest value %q",
			divergence.ID,
			frontMatter.OwnerApprovalRef,
			divergence.OwnerApprovalRef,
		)
	}
	count := 0
	for _, divergenceID := range frontMatter.DivergenceIDs {
		if divergenceID == divergence.ID {
			count++
		}
	}
	if count != 1 {
		return adrFrontMatter{}, fmt.Errorf(
			"divergence %q: ADR divergence_ids must contain the manifest divergence exactly once; found %d",
			divergence.ID,
			count,
		)
	}
	return frontMatter, nil
}

func validateADRRelativePath(relativePath string) (string, error) {
	if relativePath == "" || filepath.IsAbs(relativePath) || strings.Contains(relativePath, `\`) {
		return "", fmt.Errorf(
			"ADR path %q must be a lexical repository-relative path",
			relativePath,
		)
	}
	components := strings.Split(relativePath, "/")
	for _, component := range components {
		if component == "" || component == "." || component == ".." {
			return "", fmt.Errorf(
				"ADR path %q must not contain empty, dot, or parent components",
				relativePath,
			)
		}
	}
	if len(components) != 4 || strings.Join(components[:3], "/") != adrDirectoryPath {
		return "", fmt.Errorf(
			"ADR path %q must be strictly inside %s/",
			relativePath,
			adrDirectoryPath,
		)
	}
	if filepath.Ext(relativePath) != ".md" {
		return "", fmt.Errorf("ADR path %q must use the .md extension", relativePath)
	}
	if relativePath == adrTemplatePath {
		return "", fmt.Errorf("ADR path %q is the unreferenced proposal template", relativePath)
	}
	if _, err := adrIDFromPath(relativePath); err != nil {
		return "", err
	}
	return relativePath, nil
}

func adrIDFromPath(relativePath string) (string, error) {
	base := filepath.Base(filepath.FromSlash(relativePath))
	prefix, suffix, ok := strings.Cut(base, "-")
	if !ok || len(prefix) != 4 || suffix == "" || suffix == ".md" {
		return "", fmt.Errorf(
			"ADR path %q must start with a four-digit ADR number and a name",
			relativePath,
		)
	}
	if _, err := strconv.Atoi(prefix); err != nil {
		return "", fmt.Errorf("ADR path %q has non-numeric ADR prefix %q", relativePath, prefix)
	}
	return "ADR-" + prefix, nil
}

func parseADR(relativePath string, content []byte) (adrFrontMatter, error) {
	const opening = "---\n"
	const closing = "\n---\n"
	if !bytes.HasPrefix(content, []byte(opening)) {
		return adrFrontMatter{}, fmt.Errorf("ADR %q is missing YAML front matter", relativePath)
	}
	end := bytes.Index(content[len(opening):], []byte(closing))
	if end < 0 {
		return adrFrontMatter{}, fmt.Errorf(
			"ADR %q has unterminated YAML front matter",
			relativePath,
		)
	}
	frontMatterBytes := content[len(opening) : len(opening)+end]
	body := content[len(opening)+end+len(closing):]

	decoder := yaml.NewDecoder(bytes.NewReader(frontMatterBytes))
	decoder.KnownFields(true)
	var frontMatter adrFrontMatter
	if err := decoder.Decode(&frontMatter); err != nil {
		return adrFrontMatter{}, fmt.Errorf("decode ADR %q front matter: %w", relativePath, err)
	}
	var extra any
	if err := decoder.Decode(&extra); !errors.Is(err, io.EOF) {
		if err == nil {
			return adrFrontMatter{}, fmt.Errorf(
				"decode ADR %q front matter: multiple YAML documents are not supported",
				relativePath,
			)
		}
		return adrFrontMatter{}, fmt.Errorf("decode ADR %q front matter: %w", relativePath, err)
	}

	var fields map[string]any
	if err := yaml.Unmarshal(frontMatterBytes, &fields); err != nil {
		return adrFrontMatter{}, fmt.Errorf("decode ADR %q fields: %w", relativePath, err)
	}
	requiredFields := []string{
		"id", "title", "status", "target", "divergence_ids", "owner", "owner_approval_ref", "date",
	}
	for _, field := range requiredFields {
		if _, ok := fields[field]; !ok {
			return adrFrontMatter{}, fmt.Errorf(
				"ADR %q front matter is missing field %q",
				relativePath,
				field,
			)
		}
	}
	if strings.TrimSpace(frontMatter.ID) == "" ||
		strings.TrimSpace(frontMatter.Title) == "" ||
		strings.TrimSpace(frontMatter.Status) == "" ||
		strings.TrimSpace(frontMatter.Target) == "" ||
		strings.TrimSpace(frontMatter.Owner) == "" ||
		strings.TrimSpace(frontMatter.Date) == "" {
		return adrFrontMatter{}, fmt.Errorf(
			"ADR %q front matter contains a blank required field",
			relativePath,
		)
	}
	if frontMatter.Status != string(capability.DivergenceProposed) &&
		frontMatter.Status != string(capability.DivergenceAccepted) &&
		frontMatter.Status != string(capability.DivergenceRetired) {
		return adrFrontMatter{}, fmt.Errorf(
			"ADR %q has unknown status %q",
			relativePath,
			frontMatter.Status,
		)
	}
	requiredHeadings := []string{
		"# Context",
		"# Decision",
		"# Consequences",
		"# Evidence required to retire",
	}
	previous := -1
	for _, heading := range requiredHeadings {
		needle := []byte("\n" + heading + "\n")
		index := bytes.Index(append([]byte{'\n'}, body...), needle)
		if index < 0 || index <= previous {
			return adrFrontMatter{}, fmt.Errorf(
				"ADR %q must contain ordered heading %q",
				relativePath,
				heading,
			)
		}
		previous = index
	}
	return frontMatter, nil
}

func renderPluginsMarkdown(manifest *capability.Manifest) ([]byte, error) {
	if manifest == nil {
		return nil, errors.New("render plugins Markdown: manifest must not be nil")
	}
	counts := deriveCapabilityCounts(manifest)
	plugins := sortedCapabilities(manifest)

	var document bytes.Buffer
	document.WriteString(generatedDocumentPreamble)
	document.WriteString("\n# Plugin Capability Status\n\n")
	document.WriteString(
		"> Human-readable projection of [`pkg/capability/manifest.yaml`](../pkg/capability/manifest.yaml). " +
			"The manifest remains authoritative and contains the full evidence ledger.\n\n",
	)
	document.WriteString("## Compatibility target\n\n")
	document.WriteString("| Target | Version | Source commit | Oracle image |\n")
	document.WriteString("| --- | --- | --- | --- |\n")
	fmt.Fprintf(
		&document,
		"| `%s` | `%s` | `%s` | `%s` |\n",
		markdownCell(manifest.Target.Name),
		markdownCell(manifest.Target.Version),
		markdownCell(manifest.Target.SourceCommit),
		markdownCell(manifest.Target.Image),
	)
	document.WriteString("\n## Summary\n\n")
	fmt.Fprintf(
		&document,
		"- **%d** capabilities: **%d** APISIX defaults and **%d** extensions.\n",
		counts.total,
		counts.defaults,
		counts.total-counts.defaults,
	)
	fmt.Fprintf(
		&document,
		"- APISIX defaults: **%d** Go-applicable (**%d** full, **%d** partial, **%d** deferred) and **%d** not applicable.\n",
		counts.applicableDefaults,
		counts.fullDefaults,
		counts.partialDefaults,
		counts.deferredDefaults,
		counts.notApplicableDefaults,
	)
	verifiedEvidence, notApplicableEvidence, attentionEvidence := evidenceCounts(plugins)
	fmt.Fprintf(
		&document,
		"- Evidence claims: **%d** verified, **%d** not applicable, **%d** requiring attention.\n",
		verifiedEvidence,
		notApplicableEvidence,
		attentionEvidence,
	)
	document.WriteString("\n## Status semantics\n\n")
	document.WriteString(
		"Behavior status and evidence are independent: implemented behavior is not automatically verified.\n\n",
	)
	document.WriteString("- **full**: no known behavioral gap in the declared contract.\n")
	document.WriteString("- **partial**: one or more known gaps remain.\n")
	document.WriteString("- **deferred**: implementation is intentionally postponed.\n")
	document.WriteString("- **not_applicable**: no Go-plugin contract exists for this APISIX facility.\n\n")
	document.WriteString(
		"Evidence dimensions are Schema, Unit, Converted upstream, Differential, Real dependency, and Failure. " +
			"Platform recovery is qualified separately.\n\n",
	)
	document.WriteString("- **verified**: current auditable evidence is recorded.\n")
	document.WriteString("- **missing**, **stale**, or **flaky**: evidence requires attention.\n")
	document.WriteString("- **deferred**: evidence collection is intentionally postponed.\n")
	document.WriteString("- **not_applicable**: the dimension does not apply.\n")

	document.WriteString("\n## Project divergences\n\n")
	document.WriteString("| ID | Status | Decision |\n")
	document.WriteString("| --- | --- | --- |\n")
	for _, divergence := range manifest.Divergences {
		adrLink := strings.TrimPrefix(divergence.ADR, "docs/")
		fmt.Fprintf(
			&document,
			"| `%s` | **%s** | [`%s`](%s) |\n",
			markdownCell(divergence.ID),
			markdownCell(string(divergence.Status)),
			markdownCell(filepath.Base(divergence.ADR)),
			adrLink,
		)
	}

	document.WriteString("\n## Capabilities requiring attention\n\n")
	document.WriteString(
		"Only non-full behavior, known gaps, declared divergences, or incomplete evidence appear here.\n",
	)
	for _, plugin := range plugins {
		issues := evidenceIssues(plugin.Evidence)
		if plugin.Behavior == capability.BehaviorFull && len(plugin.KnownGaps) == 0 &&
			len(plugin.DivergenceIDs) == 0 && len(issues) == 0 {
			continue
		}
		fmt.Fprintf(&document, "\n### `%s`\n\n", markdownCell(plugin.Name))
		fmt.Fprintf(
			&document,
			"- Contract: `%s`, %s, behavior **%s**.\n",
			markdownCell(string(plugin.Namespace)),
			markdownCell(domainList(plugin.Domains)),
			markdownCell(string(plugin.Behavior)),
		)
		for _, gap := range plugin.KnownGaps {
			fmt.Fprintf(&document, "- Gap: %s\n", markdownCell(gap))
		}
		if len(plugin.DivergenceIDs) != 0 {
			fmt.Fprintf(&document, "- Divergences: %s.\n", inlineCodeList(plugin.DivergenceIDs))
		}
		if len(issues) != 0 {
			fmt.Fprintf(&document, "- Evidence: %s.\n", strings.Join(issues, ", "))
		}
	}

	document.WriteString("\n## Capability index\n\n")
	document.WriteString(
		"APISIX defaults are sorted first by name. Remaining Go extension entries follow by namespace and name.\n\n",
	)
	document.WriteString(
		"| Plugin | Namespace | APISIX default | Domains | Behavior | Evidence |\n",
	)
	document.WriteString(
		"| --- | --- | --- | --- | --- | --- |\n",
	)
	for _, plugin := range plugins {
		fmt.Fprintf(
			&document,
			"| `%s` | `%s` | %s | %s | **%s** | %s |\n",
			markdownCell(plugin.Name),
			markdownCell(string(plugin.Namespace)),
			yesNo(plugin.APISIXDefault),
			markdownCell(domainList(plugin.Domains)),
			markdownCell(string(plugin.Behavior)),
			markdownCell(evidenceSummary(plugin.Evidence)),
		)
	}
	return document.Bytes(), nil
}

