func replaceGeneratedReadmeBlock(source, summary []byte) ([]byte, error) {
	if bytes.Count(source, []byte(generatedSummaryBegin)) != 1 ||
		bytes.Count(source, []byte(generatedSummaryEnd)) != 1 {
		return nil, errors.New("generated capability summary markers must each appear exactly once")
	}
	begin := bytes.Index(source, []byte(generatedSummaryBegin))
	end := bytes.Index(source, []byte(generatedSummaryEnd))
	if begin > end {
		return nil, errors.New("generated capability summary markers are out of order")
	}
	begin += len(generatedSummaryBegin)

	var replaced bytes.Buffer
	replaced.Write(source[:begin])
	replaced.WriteByte('\n')
	replaced.WriteString(generatedSummaryNotice)
	replaced.WriteByte('\n')
	replaced.Write(bytes.Trim(summary, "\n"))
	replaced.WriteByte('\n')
	replaced.Write(source[end:])
	return replaced.Bytes(), nil
}

func deriveCapabilityCounts(manifest *capability.Manifest) capabilityCounts {
	counts := capabilityCounts{total: len(manifest.Plugins)}
	for _, plugin := range manifest.Plugins {
		if !plugin.APISIXDefault {
			continue
		}
		counts.defaults++
		switch plugin.Behavior {
		case capability.BehaviorFull:
			counts.applicableDefaults++
			counts.fullDefaults++
		case capability.BehaviorPartial:
			counts.applicableDefaults++
			counts.partialDefaults++
		case capability.BehaviorDeferred:
			counts.applicableDefaults++
			counts.deferredDefaults++
		case capability.BehaviorNotApplicable:
			counts.notApplicableDefaults++
		}
	}
	return counts
}

func sortedCapabilities(manifest *capability.Manifest) []capability.PluginCapability {
	plugins := append([]capability.PluginCapability(nil), manifest.Plugins...)
	sort.Slice(plugins, func(i, j int) bool {
		if plugins[i].APISIXDefault != plugins[j].APISIXDefault {
			return plugins[i].APISIXDefault
		}
		if plugins[i].APISIXDefault {
			return plugins[i].Name < plugins[j].Name
		}
		if plugins[i].Namespace != plugins[j].Namespace {
			return plugins[i].Namespace < plugins[j].Namespace
		}
		return plugins[i].Name < plugins[j].Name
	})
	return plugins
}

func markdownCell(value string) string {
	value = strings.ReplaceAll(value, "\r\n", "\n")
	value = strings.ReplaceAll(value, "|", `\|`)
	return strings.ReplaceAll(value, "\n", "<br>")
}

func evidenceClaims(evidence capability.Evidence) []struct {
	label string
	claim capability.EvidenceClaim
} {
	return []struct {
		label string
		claim capability.EvidenceClaim
	}{
		{label: "schema", claim: evidence.Schema},
		{label: "unit", claim: evidence.Unit},
		{label: "upstream", claim: evidence.Upstream},
		{label: "differential", claim: evidence.Differential},
		{label: "dependency", claim: evidence.RealDependency},
		{label: "failure", claim: evidence.Failure},
	}
}

func evidenceIssues(evidence capability.Evidence) []string {
	var issues []string
	for _, item := range evidenceClaims(evidence) {
		if item.claim.State == capability.EvidenceVerified ||
			item.claim.State == capability.EvidenceNotApplicable {
			continue
		}
		issues = append(issues, item.label+":"+string(item.claim.State))
	}
	return issues
}

func evidenceSummary(evidence capability.Evidence) string {
	issues := evidenceIssues(evidence)
	if len(issues) != 0 {
		return strings.Join(issues, ", ")
	}
	for _, item := range evidenceClaims(evidence) {
		if item.claim.State == capability.EvidenceVerified {
			return "verified"
		}
	}
	return "not applicable"
}

func evidenceCounts(plugins []capability.PluginCapability) (verified, notApplicable, attention int) {
	for _, plugin := range plugins {
		for _, item := range evidenceClaims(plugin.Evidence) {
			switch item.claim.State {
			case capability.EvidenceVerified:
				verified++
			case capability.EvidenceNotApplicable:
				notApplicable++
			default:
				attention++
			}
		}
	}
	return verified, notApplicable, attention
}

func inlineCodeList(values []string) string {
	rendered := make([]string, len(values))
	for index, value := range values {
		rendered[index] = "`" + markdownCell(value) + "`"
	}
	return strings.Join(rendered, ", ")
}

func domainList(domains []capability.Domain) string {
	values := make([]string, len(domains))
	for index, domain := range domains {
		values[index] = string(domain)
	}
	return strings.Join(values, ", ")
}

func yesNo(value bool) string {
	if value {
		return "yes"
	}
	return "no"
}

func renderRegistry(manifest *capability.Manifest) ([]byte, error) {
	if manifest == nil {
		return nil, errors.New("render registry: manifest must not be nil")
	}

	type registryImport struct {
		path  string
		alias string
	}
	type registryFactory struct {
		key         string
		alias       string
		constructor string
	}

	importsByPath := make(map[string]string)
	pathsByAlias := make(map[string]string)
	factories := make([]registryFactory, 0)
	seenFactories := make(map[string]struct{})
	seenEntries := make(map[string]struct{})
	for _, plugin := range manifest.Plugins {
		if len(plugin.Factories) == 0 {
			continue
		}
		if _, exists := seenEntries[plugin.Name]; exists {
			return nil, fmt.Errorf("render registry: duplicate capability identity %q", plugin.Name)
		}
		seenEntries[plugin.Name] = struct{}{}
		if err := validateGeneratedFacts(plugin); err != nil {
			return nil, err
		}
		for _, factory := range plugin.Factories {
			if _, exists := seenFactories[factory.Key]; exists {
				return nil, fmt.Errorf("render registry: duplicate factory %q", factory.Key)
			}
			seenFactories[factory.Key] = struct{}{}
			if !token.IsIdentifier(factory.ImportAlias) {
				return nil, fmt.Errorf(
					"render registry: factory %q has invalid import alias %q",
					factory.Key,
					factory.ImportAlias,
				)
			}
			if !token.IsIdentifier(factory.Constructor) {
				return nil, fmt.Errorf(
					"render registry: factory %q has invalid constructor %q",
					factory.Key,
					factory.Constructor,
				)
			}
			if alias, exists := importsByPath[factory.ImportPath]; exists &&
				alias != factory.ImportAlias {
				return nil, fmt.Errorf(
					"render registry: import %q uses aliases %q and %q",
					factory.ImportPath,
					alias,
					factory.ImportAlias,
				)
			}
			if path, exists := pathsByAlias[factory.ImportAlias]; exists &&
				path != factory.ImportPath {
				return nil, fmt.Errorf(
					"render registry: import alias %q is shared by %q and %q",
					factory.ImportAlias,
					path,
					factory.ImportPath,
				)
			}
			importsByPath[factory.ImportPath] = factory.ImportAlias
			pathsByAlias[factory.ImportAlias] = factory.ImportPath
			factories = append(factories, registryFactory{
				key:         factory.Key,
				alias:       factory.ImportAlias,
				constructor: factory.Constructor,
			})
		}
	}

	imports := make([]registryImport, 0, len(importsByPath))
	for path, alias := range importsByPath {
		imports = append(imports, registryImport{path: path, alias: alias})
	}
	sort.Slice(imports, func(i, j int) bool {
		if imports[i].path == imports[j].path {
			return imports[i].alias < imports[j].alias
		}
		return imports[i].path < imports[j].path
	})
	sort.Slice(factories, func(i, j int) bool { return factories[i].key < factories[j].key })

	var source bytes.Buffer
	source.WriteString("// Code generated by go run ./cmd/capability-gen -write; DO NOT EDIT.\n\n")
	source.WriteString("package plugin\n\n")
	source.WriteString("// Imports are rendered from manifest Factory facts.\n")
	source.WriteString("import (\n")
	for _, imported := range imports {
		fmt.Fprintf(&source, "\t%s %s\n", imported.alias, strconv.Quote(imported.path))
	}
	source.WriteString(")\n\n")
	source.WriteString("var pluginRegistry = map[string]func() Plugin{\n")
	for _, factory := range factories {
		fmt.Fprintf(
			&source,
			"\t%s: func() Plugin { return %s },\n",
			strconv.Quote(factory.key),
			constructorExpression(factory.alias, factory.constructor),
		)
	}
	source.WriteString("}\n")

	formatted, err := format.Source(source.Bytes())
	if err != nil {
		return nil, fmt.Errorf("format generated registry: %w", err)
	}
	return formatted, nil
}

func validateGeneratedFacts(plugin capability.PluginCapability) error {
	for _, phase := range plugin.Phases {
		switch phase {
		case "rewrite", "consumer_rewrite", "access", "before_proxy", "header_filter",
			"body_filter", "log", "finalizer", "protocol":
		default:
			return fmt.Errorf(
				"render registry: capability %q has unsupported phase %q",
				plugin.Name,
				phase,
			)
		}
	}
	for _, scope := range plugin.Scopes {
		switch scope {
		case "system", "global_rule", "route", "service", "consumer", "consumer_group":
		default:
			return fmt.Errorf(
				"render registry: capability %q has unsupported scope %q",
				plugin.Name,
				scope,
			)
		}
	}
	return nil
}

func constructorExpression(alias, constructor string) string {
	if constructor == "Plugin" {
		return "&" + alias + "." + constructor + "{}"
	}
	return alias + "." + constructor + "()"
}

func writeOutputs(repoRoot string, outputs []generatedOutput) error {
	root, err := openOutputRoot(repoRoot)
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()

	for _, output := range outputs {
		relativePath, err := containedOutputRelativePath(output.relativePath)
		if err != nil {
			return err
		}
		if err := rejectOutputSymlinks(root, relativePath); err != nil {
			return err
		}
		parent := filepath.Dir(relativePath)
		if parent != "." {
			if err := root.MkdirAll(parent, 0o755); err != nil {
				return fmt.Errorf("create output directory for %s: %w", output.relativePath, err)
			}
		}
		if err := rejectOutputSymlinks(root, relativePath); err != nil {
			return err
		}
		if err := root.WriteFile(relativePath, output.content, 0o644); err != nil {
			return fmt.Errorf("write %s: %w", output.relativePath, err)
		}
	}
	return nil
}

func checkOutputs(repoRoot string, outputs []generatedOutput) error {
	root, err := openOutputRoot(repoRoot)
	if err != nil {
		return err
	}
	defer func() { _ = root.Close() }()

	for _, output := range outputs {
		relativePath, err := containedOutputRelativePath(output.relativePath)
		if err != nil {
			return err
		}
		if err := rejectOutputSymlinks(root, relativePath); err != nil {
			return err
		}
		current, err := root.ReadFile(relativePath)
		if errors.Is(err, os.ErrNotExist) {
			return fmt.Errorf("%s: generated output is missing", output.relativePath)
		}
		if err != nil {
			return fmt.Errorf("read %s: %w", output.relativePath, err)
		}
		if !bytes.Equal(current, output.content) {
			return fmt.Errorf("%s: generated output is stale", output.relativePath)
		}
	}
	return nil
}

func readRootedFile(root *os.Root, relativePath string) ([]byte, error) {
	relativePath, err := containedOutputRelativePath(relativePath)
	if err != nil {
		return nil, err
	}
	if err := rejectOutputSymlinks(root, relativePath); err != nil {
		return nil, err
	}
	content, err := root.ReadFile(relativePath)
	if err != nil {
		return nil, fmt.Errorf("read %s: %w", relativePath, err)
	}
	return content, nil
}

func openOutputRoot(repoRoot string) (*os.Root, error) {
	rootPath, err := canonicalRepoRoot(repoRoot)
	if err != nil {
		return nil, err
	}
	root, err := os.OpenRoot(rootPath)
	if err != nil {
		return nil, fmt.Errorf("open repository root %q: %w", repoRoot, err)
	}
	return root, nil
}

func canonicalRepoRoot(repoRoot string) (string, error) {
	rootPath, err := filepath.Abs(filepath.Clean(repoRoot))
	if err != nil {
		return "", fmt.Errorf("clean repository root: %w", err)
	}
	rootPath, err = filepath.EvalSymlinks(rootPath)
	if err != nil {
		return "", fmt.Errorf("resolve repository root: %w", err)
	}
	return rootPath, nil
}

func containedOutputRelativePath(relativePath string) (string, error) {
	if filepath.IsAbs(relativePath) {
		return "", fmt.Errorf("output path %q escapes repository root", relativePath)
	}
	relative := filepath.Clean(filepath.FromSlash(relativePath))
	if relative == ".." || strings.HasPrefix(relative, ".."+string(filepath.Separator)) {
		return "", fmt.Errorf("output path %q escapes repository root", relativePath)
	}
	return relative, nil
}

func rejectOutputSymlinks(root *os.Root, relativePath string) error {
	return rejectRootedSymlinks(root, relativePath, "output path")
}

func rejectRootedSymlinks(root *os.Root, relativePath, pathKind string) error {
	currentPath := ""
	for component := range strings.SplitSeq(filepath.ToSlash(relativePath), "/") {
		if component == "" || component == "." {
			continue
		}
		currentPath = filepath.Join(currentPath, component)
		info, err := root.Lstat(currentPath)
		if errors.Is(err, os.ErrNotExist) {
			return nil
		}
		if err != nil {
			return fmt.Errorf("inspect %s %q: %w", pathKind, relativePath, err)
		}
		if info.Mode()&os.ModeSymlink != 0 {
			return fmt.Errorf(
				"%s %q contains symbolic link %q",
				pathKind,
				relativePath,
				currentPath,
			)
		}
	}
	return nil
}
