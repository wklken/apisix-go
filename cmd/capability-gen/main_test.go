func writeManifestADRs(t *testing.T, root string, manifest *capability.Manifest) {
	t.Helper()
	for _, divergence := range manifest.Divergences {
		if divergence.Status != capability.DivergenceAccepted {
			continue
		}
		base := filepath.Base(filepath.FromSlash(divergence.ADR))
		number := strings.SplitN(base, "-", 2)[0]
		writeADR(t, root, divergence.ADR, validADRDocument(
			"ADR-"+number,
			"accepted",
			[]string{divergence.ID},
			"wklken",
			divergence.Target,
			divergence.OwnerApprovalRef,
		))
	}
}

func writeADR(t *testing.T, root, relativePath, content string) {
	t.Helper()
	path := filepath.Join(root, filepath.FromSlash(relativePath))
	if err := os.MkdirAll(filepath.Dir(path), 0o755); err != nil {
		t.Fatal(err)
	}
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
}

func validADRDocument(id, status string, divergenceIDs []string, owner, target, approval string) string {
	quotedIDs := make([]string, len(divergenceIDs))
	for index, divergenceID := range divergenceIDs {
		quotedIDs[index] = fmt.Sprintf("%q", divergenceID)
	}
	return fmt.Sprintf(`---
id: %s
title: Test divergence
status: %s
target: %s
divergence_ids: [%s]
owner: %s
owner_approval_ref: %q
date: 2026-08-23
---

# Context

Pinned behavior.

# Decision

Exact decision.

# Consequences

Known consequences.

# Evidence required to retire

Exact retirement evidence.
`, id, status, target, strings.Join(quotedIDs, ", "), owner, approval)
}

func TestCheckDetectsDrift(t *testing.T) {
	manifest, err := capability.Load()
	if err != nil {
		t.Fatal(err)
	}
	generated, err := renderRegistry(manifest)
	if err != nil {
		t.Fatal(err)
	}
	outputs := []generatedOutput{{relativePath: registryOutputPath, content: generated}}
	root := t.TempDir()
	if err := writeOutputs(root, outputs); err != nil {
		t.Fatal(err)
	}

	path := filepath.Join(root, filepath.FromSlash(registryOutputPath))
	drifted := append([]byte(nil), generated...)
	drifted[0] ^= 1
	if err := os.WriteFile(path, drifted, 0o644); err != nil {
		t.Fatal(err)
	}
	if err := checkOutputs(root, outputs); err == nil {
		t.Fatal("checkOutputs() error = nil, want generated drift")
	} else if got, want := err.Error(), registryOutputPath+": generated output is stale"; got != want {
		t.Fatalf("checkOutputs() error = %q, want %q", got, want)
	}
}

