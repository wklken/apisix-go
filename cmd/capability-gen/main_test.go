func TestRenderPluginsMarkdownSeparatesBehaviorAndEvidence(t *testing.T) {
	manifest := loadManifest(t)
	generated, err := renderPluginsMarkdown(manifest)
	if err != nil {
		t.Fatal(err)
	}

	for _, text := range []string{
		"Code generated by go run ./cmd/capability-gen -write; DO NOT EDIT.",
		"Behavior status",
		"Capabilities requiring attention",
		"Project divergences",
		"Capability index",
		"Schema",
		"Unit",
		"Converted upstream",
		"Differential",
		"Real dependency",
		"Failure",
	} {
		if !bytes.Contains(generated, []byte(text)) {
			t.Fatalf("generated plugins.md missing %q", text)
		}
	}
	if bytes.Contains(generated, []byte("owner:")) ||
		bytes.Contains(generated, []byte("refs:")) ||
		bytes.Contains(generated, []byte("| Behavior summary |")) {
		t.Fatal("generated plugins.md exposes audit-ledger detail in the human status view")
	}
	if len(generated) > 50_000 {
		t.Fatalf("generated plugins.md is %d bytes, want a concise document <= 50000 bytes", len(generated))
	}
	for lineNumber, line := range bytes.Split(generated, []byte("\n")) {
		if len(line) > 500 {
			t.Fatalf("generated plugins.md line %d is %d bytes, want <= 500", lineNumber+1, len(line))
		}
	}
	if bytes.Contains(generated, []byte("| Recovery |")) {
		t.Fatal("generated plugins.md must not project platform recovery onto plugin rows")
	}
	for _, field := range []string{
		manifest.Target.Name,
		manifest.Target.Version,
		manifest.Target.SourceCommit,
		manifest.Target.Image,
		"manifest remains authoritative",
	} {
		if !bytes.Contains(generated, []byte(field)) {
			t.Fatalf("generated plugins.md missing target/projection field %q", field)
		}
	}
}

func TestRenderPluginsMarkdownSortsDefaultsBeforeExtensions(t *testing.T) {
	manifest := loadManifest(t)
	generated, err := renderPluginsMarkdown(manifest)
	if err != nil {
		t.Fatal(err)
	}

	defaults := make([]capability.PluginCapability, 0)
	extensions := make([]capability.PluginCapability, 0)
	for _, plugin := range manifest.Plugins {
		if plugin.APISIXDefault {
			defaults = append(defaults, plugin)
		} else {
			extensions = append(extensions, plugin)
		}
	}
	sort.Slice(defaults, func(i, j int) bool { return defaults[i].Name < defaults[j].Name })
	sort.Slice(extensions, func(i, j int) bool {
		if extensions[i].Namespace != extensions[j].Namespace {
			return extensions[i].Namespace < extensions[j].Namespace
		}
		return extensions[i].Name < extensions[j].Name
	})
	positions := make([]int, 0, len(manifest.Plugins))
	for _, plugin := range defaults {
		row := []byte("| `" + plugin.Name + "` | `" + string(plugin.Namespace) + "` |")
		positions = append(positions, bytes.Index(generated, row))
	}
	for _, plugin := range extensions {
		row := []byte("| `" + plugin.Name + "` | `" + string(plugin.Namespace) + "` |")
		positions = append(positions, bytes.Index(generated, row))
	}
	for index, position := range positions {
		if position < 0 {
			t.Fatalf("sorted plugin row %d is missing", index)
		}
		if index > 0 && positions[index-1] >= position {
			t.Fatalf(
				"plugin rows are not in deterministic default/extension order at %d: %d >= %d",
				index,
				positions[index-1],
				position,
			)
		}
	}
}

