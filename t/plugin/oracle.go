type DifferentialSelection struct {
	Plugins    []string `json:"plugins"`
	Cases      []string `json:"cases"`
	ShardIndex int      `json:"shard_index"`
	ShardCount int      `json:"shard_count"`
}

func selectDifferentialCases(
	all []DifferentialCase,
	selection DifferentialSelection,
) ([]DifferentialCase, DifferentialSelection, error) {
	if selection.ShardCount < 1 {
		return nil, DifferentialSelection{}, fmt.Errorf(
			"differential shard count = %d, want at least 1",
			selection.ShardCount,
		)
	}
	if selection.ShardIndex < 0 || selection.ShardIndex >= selection.ShardCount {
		return nil, DifferentialSelection{}, fmt.Errorf(
			"differential shard index = %d, want 0 <= index < %d",
			selection.ShardIndex,
			selection.ShardCount,
		)
	}

	caseByName := make(map[string]DifferentialCase, len(all))
	knownPlugins := make(map[string]struct{}, len(all))
	for _, spec := range all {
		if strings.TrimSpace(spec.Name) == "" || strings.TrimSpace(spec.Plugin) == "" {
			return nil, DifferentialSelection{}, fmt.Errorf(
				"runtime differential case has incomplete identity: name=%q plugin=%q",
				spec.Name,
				spec.Plugin,
			)
		}
		if _, exists := caseByName[spec.Name]; exists {
			return nil, DifferentialSelection{}, fmt.Errorf(
				"runtime differential cases contain duplicate case %q",
				spec.Name,
			)
		}
		caseByName[spec.Name] = spec
		knownPlugins[spec.Plugin] = struct{}{}
	}
	if len(caseByName) == 0 {
		return nil, DifferentialSelection{}, errors.New("runtime differential cases are empty")
	}

	plugins, err := normalizeDifferentialSelectors("plugin", selection.Plugins, knownPlugins)
	if err != nil {
		return nil, DifferentialSelection{}, err
	}
	knownCases := make(map[string]struct{}, len(caseByName))
	for name := range caseByName {
		knownCases[name] = struct{}{}
	}
	cases, err := normalizeDifferentialSelectors("case", selection.Cases, knownCases)
	if err != nil {
		return nil, DifferentialSelection{}, err
	}
	normalized := DifferentialSelection{
		Plugins:    plugins,
		Cases:      cases,
		ShardIndex: selection.ShardIndex,
		ShardCount: selection.ShardCount,
	}

	pluginFilter := makeStringSet(plugins)
	caseFilter := makeStringSet(cases)
	sorted := append([]DifferentialCase(nil), all...)
	sort.Slice(sorted, func(i, j int) bool { return sorted[i].Name < sorted[j].Name })
	filtered := make([]DifferentialCase, 0, len(sorted))
	for _, spec := range sorted {
		if len(pluginFilter) > 0 {
			if _, selected := pluginFilter[spec.Plugin]; !selected {
				continue
			}
		}
		if len(caseFilter) > 0 {
			if _, selected := caseFilter[spec.Name]; !selected {
				continue
			}
		}
		filtered = append(filtered, spec)
	}
	if len(filtered) == 0 {
		return nil, DifferentialSelection{}, errors.New("differential selection selects no differential cases")
	}

	selected := make([]DifferentialCase, 0, len(filtered))
	for index, spec := range filtered {
		if index%normalized.ShardCount == normalized.ShardIndex {
			selected = append(selected, spec)
		}
	}
	if len(selected) == 0 {
		return nil, DifferentialSelection{}, errors.New("differential shard selects no differential cases")
	}
	return selected, normalized, nil
}

func normalizeDifferentialSelectors(
	kind string,
	selectors []string,
	known map[string]struct{},
) ([]string, error) {
	normalized := make([]string, 0, len(selectors))
	seen := make(map[string]struct{}, len(selectors))
	for _, raw := range selectors {
		selector := strings.TrimSpace(raw)
		if selector == "" {
			return nil, fmt.Errorf("blank %s selector", kind)
		}
		if _, exists := seen[selector]; exists {
			return nil, fmt.Errorf("duplicate %s selector %q", kind, selector)
		}
		if _, exists := known[selector]; !exists {
			return nil, fmt.Errorf("unknown %s selector %q", kind, selector)
		}
		seen[selector] = struct{}{}
		normalized = append(normalized, selector)
	}
	sort.Strings(normalized)
	return normalized, nil
}

func makeStringSet(values []string) map[string]struct{} {
	set := make(map[string]struct{}, len(values))
	for _, value := range values {
		set[value] = struct{}{}
	}
	return set
}

