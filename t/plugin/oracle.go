func mergeDifferentialRuntimeOverlay(runtime, overlay map[string]any) error {
	for key, value := range overlay {
		if key != "plugin_attr" && key != "nginx_config" {
			return fmt.Errorf("differential runtime overlay may not replace harness-owned %q", key)
		}
		source, ok := value.(map[string]any)
		if !ok {
			return fmt.Errorf("differential runtime overlay %q must be an object", key)
		}
		target, ok := runtime[key].(map[string]any)
		if !ok {
			target = make(map[string]any)
			runtime[key] = target
		}
		mergeDifferentialRuntimeMap(target, source)
	}
	return nil
}

func mergeDifferentialRuntimeMap(target, source map[string]any) {
	for key, value := range source {
		sourceMap, sourceIsMap := value.(map[string]any)
		targetMap, targetIsMap := target[key].(map[string]any)
		if sourceIsMap && targetIsMap {
			mergeDifferentialRuntimeMap(targetMap, sourceMap)
			continue
		}
		target[key] = value
	}
}

