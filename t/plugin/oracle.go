var sha256DigestPattern = regexp.MustCompile(`^sha256:[0-9a-f]{64}$`)

// OracleIdentity is the complete identity needed to reproduce the official
// APISIX compatibility oracle. The image tag is descriptive; execution must
// use ImageReference, which is digest qualified.
type OracleIdentity struct {
	SchemaVersion    int    `yaml:"schema_version"           json:"schema_version"`
	ImageTag         string `yaml:"image_tag"                json:"image_tag"`
	ImageRepository  string `yaml:"image_repository"         json:"image_repository"`
	ImageIndexDigest string `yaml:"image_index_digest"       json:"image_index_digest"`
	ImageLinuxAMD64  string `yaml:"image_linux_amd64_digest" json:"image_linux_amd64_digest"`
	SourceRepository string `yaml:"source_repository"        json:"source_repository"`
	SourceCommit     string `yaml:"source_commit"            json:"source_commit"`
	ExpectedVersion  string `yaml:"expected_version"         json:"expected_version"`
}

func (identity OracleIdentity) ImageReference() string {
	return identity.ImageRepository + "@" + identity.ImageLinuxAMD64
}

func (identity OracleIdentity) Validate() error {
	if identity.SchemaVersion != 1 {
		return fmt.Errorf("oracle schema_version = %d, want 1", identity.SchemaVersion)
	}
	if identity.ImageTag != compatibilityOracleImage {
		return fmt.Errorf(
			"oracle image_tag = %q, want %q",
			identity.ImageTag,
			compatibilityOracleImage,
		)
	}
	if identity.ImageRepository != compatibilityOracleRepository {
		return fmt.Errorf(
			"oracle image_repository = %q, want %q",
			identity.ImageRepository,
			compatibilityOracleRepository,
		)
	}
	if identity.ImageLinuxAMD64 != compatibilityOracleImageDigest {
		return fmt.Errorf(
			"oracle linux/amd64 digest = %q, want %q",
			identity.ImageLinuxAMD64,
			compatibilityOracleImageDigest,
		)
	}
	if !sha256DigestPattern.MatchString(identity.ImageIndexDigest) {
		return fmt.Errorf(
			"oracle image index digest is not sha256-qualified: %q",
			identity.ImageIndexDigest,
		)
	}
	if !sha256DigestPattern.MatchString(identity.ImageLinuxAMD64) {
		return fmt.Errorf(
			"oracle linux/amd64 digest is not sha256-qualified: %q",
			identity.ImageLinuxAMD64,
		)
	}
	if identity.SourceRepository != "https://github.com/apache/apisix" {
		return fmt.Errorf("oracle source_repository = %q", identity.SourceRepository)
	}
	if identity.SourceCommit != compatibilityOracleSourceCommit {
		return fmt.Errorf(
			"oracle source_commit = %q, want %q",
			identity.SourceCommit,
			compatibilityOracleSourceCommit,
		)
	}
	if identity.ExpectedVersion != compatibilityOracleVersion {
		return fmt.Errorf(
			"oracle expected_version = %q, want %q",
			identity.ExpectedVersion,
			compatibilityOracleVersion,
		)
	}
	return nil
}

func loadOracleIdentity(path string) (OracleIdentity, error) {
	data, err := os.ReadFile(path)
	if err != nil {
		return OracleIdentity{}, fmt.Errorf("read oracle identity %s: %w", path, err)
	}
	decoder := yaml.NewDecoder(strings.NewReader(string(data)))
	decoder.KnownFields(true)
	var identity OracleIdentity
	if err := decoder.Decode(&identity); err != nil {
		return OracleIdentity{}, fmt.Errorf("decode oracle identity %s: %w", path, err)
	}
	var extra any
	if err := decoder.Decode(&extra); !errors.Is(err, io.EOF) {
		if err == nil {
			return OracleIdentity{}, fmt.Errorf(
				"oracle identity %s contains multiple YAML documents",
				path,
			)
		}
		return OracleIdentity{}, fmt.Errorf("decode oracle identity %s: %w", path, err)
	}
	if err := identity.Validate(); err != nil {
		return OracleIdentity{}, err
	}
	return identity, nil
}

