func projectDifferentialConfig(config map[string]any, endpoint string) (map[string]any, error) {
	data, err := yaml.Marshal(config)
	if err != nil {
		return nil, fmt.Errorf("marshal differential config: %w", err)
	}
	var projected map[string]any
	if err := yaml.Unmarshal(data, &projected); err != nil {
		return nil, fmt.Errorf("clone differential config: %w", err)
	}
	if endpoint == "" {
		serialized := string(data)
		if strings.Contains(serialized, differentialFixturePlaceholder) ||
			strings.Contains(serialized, differentialFixtureHostPlaceholder) ||
			strings.Contains(serialized, differentialFixturePortPlaceholder) {
			return nil, errors.New("differential fixture endpoint is required for unresolved placeholders")
		}
		return projected, nil
	}
	host, portText, err := net.SplitHostPort(endpoint)
	if err != nil {
		return nil, fmt.Errorf("split differential fixture endpoint %q: %w", endpoint, err)
	}
	port, err := strconv.Atoi(portText)
	if err != nil {
		return nil, fmt.Errorf("parse differential fixture port %q: %w", portText, err)
	}
	replaceDifferentialPlaceholders(projected, endpoint, host, portText, port)
	return projected, nil
}

func replaceDifferentialPlaceholders(value any, endpoint, host, portText string, port int) {
	switch typed := value.(type) {
	case map[string]any:
		for key, child := range typed {
			projectedKey := replaceDifferentialFixtureStrings(key, endpoint, host, portText)
			if projectedKey != key {
				delete(typed, key)
				typed[projectedKey] = child
				key = projectedKey
			}
			if stringValue, ok := child.(string); ok {
				if stringValue == differentialFixturePortPlaceholder {
					typed[key] = port
				} else {
					typed[key] = replaceDifferentialFixtureStrings(stringValue, endpoint, host, portText)
				}
				continue
			}
			replaceDifferentialPlaceholders(child, endpoint, host, portText, port)
		}
	case []any:
		for i, child := range typed {
			if stringValue, ok := child.(string); ok {
				if stringValue == differentialFixturePortPlaceholder {
					typed[i] = port
				} else {
					typed[i] = replaceDifferentialFixtureStrings(stringValue, endpoint, host, portText)
				}
				continue
			}
			replaceDifferentialPlaceholders(child, endpoint, host, portText, port)
		}
	}
}

func replaceDifferentialFixtureStrings(value, endpoint, host, port string) string {
	value = strings.ReplaceAll(value, differentialFixturePlaceholder, endpoint)
	value = strings.ReplaceAll(value, differentialFixtureHostPlaceholder, host)
	return strings.ReplaceAll(value, differentialFixturePortPlaceholder, port)
}

