func writeDifferentialArtifact(path string, artifact DifferentialArtifact) error {
	if path == "" {
		return errors.New("differential artifact path is empty")
	}
	if _, err := os.Stat(path); err == nil {
		return fmt.Errorf("differential artifact already exists: %s", path)
	} else if !errors.Is(err, os.ErrNotExist) {
		return fmt.Errorf("inspect differential artifact %s: %w", path, err)
	}
	data, err := json.MarshalIndent(artifact, "", "  ")
	if err != nil {
		return fmt.Errorf("marshal differential artifact: %w", err)
	}
	data = append(data, '\n')
	if err := os.MkdirAll(filepath.Dir(path), 0o700); err != nil {
		return fmt.Errorf("create differential artifact directory: %w", err)
	}
	temp, err := os.CreateTemp(filepath.Dir(path), ".differential-artifact-*")
	if err != nil {
		return fmt.Errorf("create differential artifact temp: %w", err)
	}
	tempPath := temp.Name()
	defer func() {
		_ = temp.Close()
		_ = os.Remove(tempPath)
	}()
	if err := temp.Chmod(0o600); err != nil {
		return fmt.Errorf("chmod differential artifact: %w", err)
	}
	if _, err := temp.Write(data); err != nil {
		return fmt.Errorf("write differential artifact: %w", err)
	}
	if err := temp.Sync(); err != nil {
		return fmt.Errorf("sync differential artifact: %w", err)
	}
	if err := temp.Close(); err != nil {
		return fmt.Errorf("close differential artifact: %w", err)
	}
	if err := os.Link(tempPath, path); errors.Is(err, os.ErrExist) {
		return fmt.Errorf("differential artifact already exists: %s", path)
	} else if err != nil {
		return fmt.Errorf("publish differential artifact: %w", err)
	}
	if err := os.Remove(tempPath); err != nil {
		return fmt.Errorf("clean published differential artifact temp: %w", err)
	}
	return nil
}

func repositoryRootFromWorkingDirectory() (string, error) {
	if configured := strings.TrimSpace(os.Getenv("APISIX_GO_REPO_ROOT")); configured != "" {
		return filepath.Abs(configured)
	}
	workingDirectory, err := os.Getwd()
	if err != nil {
		return "", err
	}
	for current := workingDirectory; ; current = filepath.Dir(current) {
		if _, err := os.Stat(filepath.Join(current, "validation", "oracle.yaml")); err == nil {
			return current, nil
		}
		parent := filepath.Dir(current)
		if parent == current {
			break
		}
	}
	return "", fmt.Errorf("cannot locate repository root from %s", workingDirectory)
}

