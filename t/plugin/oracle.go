func validateDifferentialFixtureRequestWindow(fixture DifferentialFixture) error {
	if fixture.RequestWindowQuietMillis < 0 || fixture.RequestWindowQuietMillis > 10_000 {
		return fmt.Errorf(
			"differential fixture request_window_quiet_millis = %d, want 0..10000",
			fixture.RequestWindowQuietMillis,
		)
	}
	if fixture.RequestWindowQuietMillis == 0 {
		return nil
	}
	if fixture.ExpectedCalls <= 0 {
		return fmt.Errorf(
			"differential fixture request window expected_calls = %d, want greater than 0",
			fixture.ExpectedCalls,
		)
	}
	if fixture.CollectTimeoutMillis > 0 &&
		fixture.RequestWindowQuietMillis >= fixture.CollectTimeoutMillis {
		return fmt.Errorf(
			"differential fixture request_window_quiet_millis = %d, want less than collect_timeout_millis %d",
			fixture.RequestWindowQuietMillis,
			fixture.CollectTimeoutMillis,
		)
	}
	return nil
}

